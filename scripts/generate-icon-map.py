#!/usr/bin/env python3
"""Generate a static app-icon map for the launcher from its dev catalog.

Reads launcher/apps.js (id -> icon) and writes launcher/icon-map.js as
window.TV_ICONS. The map is committed and shipped inside the launcher IPK,
so the Home grid renders known icons deterministically from local assets
instead of relying on the TV's inventory to serve icon paths.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APPS_JS = ROOT / 'launcher/apps.js'
OUT = ROOT / 'launcher/icon-map.js'


def main():
    if not APPS_JS.exists():
        sys.exit('launcher/apps.js not found; run sync-apps.py first?')
    content = APPS_JS.read_text()
    match = re.search(r'window\.TV_APPS\s*=\s*(\{.*?\});', content, re.DOTALL)
    if not match:
        sys.exit('Could not find TV_APPS in apps.js')
    tv_apps = json.loads(match.group(1))
    icons = {}
    missing = []
    for app in tv_apps.get('apps', []):
        icon = app.get('icon') or ''
        if icon and icon.startswith('icons/'):
            icons[app['id']] = icon
            if not (ROOT / 'launcher' / icon).exists():
                missing.append(icon)
    if missing:
        print('WARNING missing icon files:', ', '.join(missing))
    lines = [
        '// Generated by scripts/generate-icon-map.py. Do not edit by hand.',
        '// Static mapping of app id -> bundled icon asset, shipped in the IPK.',
        'window.TV_ICONS = ' + json.dumps(icons, indent=2, sort_keys=True) + ';\n',
    ]
    OUT.write_text('\n'.join(lines))
    print('wrote', OUT, 'with', len(icons), 'icons')


if __name__ == '__main__':
    main()
