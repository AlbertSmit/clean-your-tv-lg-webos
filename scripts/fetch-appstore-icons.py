#!/usr/bin/env python3
"""Fetch high-quality App Store / iTunes artwork for launcher icon overrides.

Writes launcher/icon-overrides.js (window.TV_ICON_OVERRIDES) and downloads
icons into launcher/icons-tvos/<appid>.jpg at 1024x1024 when available.

Usage: python3 scripts/fetch-appstore-icons.py [--limit N] [--refresh]
"""
import argparse
import json
import sys
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / 'launcher/icons-tvos'
OUT_MAP = ROOT / 'launcher/icon-overrides.js'

# LG app id -> (iTunes search term, country)
APPS = {
    'netflix': ('Netflix', 'us'),
    'youtube.leanback.v4': ('YouTube', 'us'),
    'com.apple.appletv': ('Apple TV', 'us'),
    'com.apple.applemusic': ('Apple Music', 'us'),
    'cdp-30': ('Plex', 'us'),
    'com.disney.disneyplus-prod': ('Disney+', 'us'),
    'viaplay-lg': ('Viaplay', 'se'),
    'com.hbo.hbomax': ('HBO Max', 'us'),
    'amazon': ('Amazon Prime Video', 'us'),
    'com.skyshowtime.tv': ('SkyShowtime', 'nl'),
    'amazon.alexa.view': ('Amazon Alexa', 'us'),
    'ui30': ('Rakuten TV', 'es'),
    'tv.solocoo.m7cp': ('Canal+', 'nl'),
    'pathe': ('Pathé Thuis', 'nl'),
    'triple.nos.app': ('NOS', 'nl'),
    'npo': ('NPO Start', 'nl'),
    'sbs.eu.temp': ('KIJK', 'nl'),
    'rtl': ('RTL XL', 'nl'),
    'videoland2021': ('Videoland', 'nl'),
    'nlziet': ('NLZIET', 'nl'),
    'com.miniclip.eightballpool': ('8 Ball Pool', 'us'),
}

def search(term, country, limit=6):
    url = 'https://itunes.apple.com/search?' + urllib.parse.urlencode({
        'term': term, 'entity': 'software', 'country': country, 'limit': limit,
    })
    with urllib.request.urlopen(url, timeout=20) as r:
        return json.load(r).get('results', [])

def pick(results, term):
    tl = term.lower()
    for r in results:
        name = (r.get('trackName') or '').lower()
        seller = (r.get('sellerName') or '').lower()
        if tl in name or tl in seller:
            # Prefer the artwork with the highest available resolution.
            art = r.get('artworkUrl512') or r.get('artworkUrl100') or r.get('artworkUrl60')
            if art:
                return art
    return None

def upgrade(art):
    # mzstatic thumbnails honor a requested size in the URL tail.
    if '/512x512bb.' in art:
        return art.replace('/512x512bb.', '/1024x1024bb.')
    if '/512x512.' in art:
        return art.replace('/512x512.', '/1024x1024.')
    return art

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--limit', type=int, default=0, help='only fetch first N apps')
    ap.add_argument('--refresh', action='store_true', help='refetch even if file exists')
    args = ap.parse_args()

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    overrides = {}
    items = list(APPS.items())
    if args.limit:
        items = items[: args.limit]

    for app_id, (term, country) in items:
        target = OUT_DIR / (app_id + '.jpg')
        if target.exists() and not args.refresh:
            overrides[app_id] = 'icons-tvos/' + target.name
            print(f'skip  {app_id} (exists)')
            continue
        try:
            results = search(term, country)
            art = pick(results, term)
            if not art:
                print(f'warn {app_id}: no artwork for {term!r}')
                continue
            url = upgrade(art)
            req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
            with urllib.request.urlopen(req, timeout=30) as r:
                data = r.read()
            if not data[:3] in (b'\xff\xd8\xff', b'\x89PNG'):
                print(f'warn {app_id}: not an image ({len(data)} bytes)')
                continue
            target.write_bytes(data)
            overrides[app_id] = 'icons-tvos/' + target.name
            print(f'ok   {app_id} <- {url} ({len(data)} bytes)')
        except Exception as exc:  # noqa: BLE001
            print(f'warn {app_id}: {exc}')

    if not overrides:
        print('nothing fetched; nothing written')
        return
    lines = [
        '// Generated by scripts/fetch-appstore-icons.py. Do not edit by hand.',
        '// High-resolution App Store artwork overrides, keyed by LG app id.',
        'window.TV_ICON_OVERRIDES = ' + json.dumps(overrides, indent=2, sort_keys=True) + ';\n',
    ]
    OUT_MAP.write_text('\n'.join(lines))
    print('wrote', OUT_MAP, 'with', len(overrides), 'overrides')

if __name__ == '__main__':
    main()
